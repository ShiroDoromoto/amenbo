// THE WIRING SEAM (read side).
//
// At startup, one round trip to core (the Tauri command `snapshot`) fetches the read data every
// screen needs and parks it in a module cache. Readers read that cache **synchronously**. Outside
// Tauri (a plain `npm run dev` browser) it falls back to the mock fixtures, so the frontend can be
// iterated on its own.
//
// Invariant: only domain state (the shared data whose source of truth is SQLite) belongs on
// `Snapshot`. Not UI-local state (selection, tab, filter, draft — React useState), and not
// device-local UI preferences (theme — localStorage): putting them here would drag every view
// through the wholesale swap that each write performs. Nor do the bulk task and decision rows of
// the list and board live in the cache — the `tasks`/`decisions` fields are **for the browser mock
// fallback only** and core leaves them empty on the Tauri path, where the paging hooks in
// `core/reads` (task_page/decision_page/tasks_by_ids/decisions_by_ids) fetch a window at a time and
// keep memory bounded.
import type { TaskCard } from "../mock/types";
import type {
  DecisionRefDto,
  DecisionDto,
  DoctorIssueDto,
  StartupHealthDto,
  StoreSignatureDto,
  VersionStatusDto,
  Snapshot as SnapshotDto,
} from "../bindings/bindings";
import { invalidateAllQueries, invalidateScopes, recheckSetupAgain } from "./query";
import { drainChanges, hasChangeCursor, takeChangeCursor } from "./changes";
import { applyPerfConfig, invoke } from "./ipc";
import { clearDismissedUpdate } from "./updateDismissed";

// The wire types are generated by ts-rs. Re-export them under the app's names, and extend only the
// types that gain a client-only field.
/** A cross-link to a decision or task (id, display name, and the conversational ref `#N`). */
export type DecisionRef = DecisionRefDto;
export type DecisionStatus = DecisionDto["status"];
/** One decision record. */
export type Decision = DecisionDto;
// Findings from the startup integrity check. The GUI surfaces any warning in a read-only banner and
// never repairs on its own. An issue is the same type the doctor surface uses: no prose of its own,
// the surface composes the sentence from kind and params.
export type StartupIssue = DoctorIssueDto;
export type StartupHealth = StartupHealthDto;

/**
 * The GUI snapshot. Its wire half is the generated `SnapshotDto` (roster, projects, activity, config
 * and so on). `tasks`/`decisions` are **for the browser mock fallback only** — core never sends
 * them, and `loadSnapshot` fills them with empty arrays to satisfy the non-optional type. The Tauri
 * path never reads those two; the paging hooks fetch a window at a time, keeping memory bounded.
 */
export type Snapshot = SnapshotDto & {
  tasks: TaskCard[];
  decisions: Decision[];
};

const EMPTY: Snapshot = {
  language: null,
  dateLocale: null, // unset means "the one that goes with the language" — see dateLocale() in i18n
  roster: [],
  projects: [],
  tasks: [],
  decisions: [],
  activity: [],
  startupHealth: { issues: [] },
  versionStatus: { appVersion: "", updateAvailable: false, newerVersion: null },
  perfLog: null,
  updateCheck: true,
  autostart: false, // off until asked for — nothing is registered at login by default
  tickConsent: null, // nobody has been asked about the hourly tick yet
  tickRemovalLeavesARow: false, // a build fact; the real one arrives with the first snapshot
  defaultView: "board", // what a project created without a view of its own opens in (core's default)
  signature: { file: "", config: "", version: "" }, // never compared: `lastSignature` is set from a real read only
};

let cache: Snapshot = EMPTY;
const listeners = new Set<() => void>();

/**
 * The payload announcing the moment an outside write (AI or CLI) landed in the GUI. It carries the
 * bare minimum a visual effect needs to distinguish why and when — never the effect itself.
 */
export interface StoreChangeReflected {
  /** Where it came from: `live` = the watcher's normal targeted path (a scope), `gap` = a full re-read after a detected gap. */
  reason: "live" | "gap";
  /** When it landed (epoch ms). */
  at: number;
}

// Subscribers to outside writes landing — deliberately separate from the domain snapshot's
// `listeners`, so a visual effect does not ride along with every domain re-render.
const reflectionListeners = new Set<(r: StoreChangeReflected) => void>();

/**
 * Subscribes to the moment an outside write (AI or CLI) lands in the GUI — the substrate every
 * visual effect builds on. It fires **only for outside writes**: the store subscription has already filtered
 * our own (every leg of the signature unchanged) and the commits that touch nothing this screen draws.
 * Outside Tauri the subscription is a no-op, so nothing ever fires. The returned function unsubscribes.
 */
export function subscribeStoreChangeReflected(fn: (r: StoreChangeReflected) => void): () => void {
  reflectionListeners.add(fn);
  return () => reflectionListeners.delete(fn);
}

/**
 * Notifies subscribers that an outside write landed. **The store subscription is the only caller** (both
 * the gap and the normal path, in the window that read, and in the other one as it takes what was read),
 * and it calls this only after filtering out our own writes — which is what makes the signal mean
 * "outside". No other module may call it, or that meaning is lost.
 */
export function notifyStoreChangeReflected(r: StoreChangeReflected): void {
  for (const l of reflectionListeners) l(r);
}

// Generation counter for data that can change who is *in* the mailbox. `loadSnapshot` and
// `applySnapshot` (a re-read of real domain data) and `notifyInboxChanged` (a device-local inbox
// archive change) bump it. `notifyDataChanged` — the read-receipt path, i.e. clicking an item read
// — deliberately **does not**: marking read leaves membership untouched, so there is nothing to
// wake the mailbox for. The mailbox re-derives its set of inbox ids only when this generation
// moves, which is what stops a recompute on every read click.
let inboxDataGeneration = 0;

/** The mailbox-affecting data generation: bumped by a data re-read or an archive change, never by marking read. */
export function getInboxDataGeneration(): number {
  return inboxDataGeneration;
}

/** Whether we are running inside the Tauri shell — i.e. whether core can be invoked at all. */
export function inTauri(): boolean {
  return typeof window !== "undefined" && "__TAURI_INTERNALS__" in window;
}

/** The current snapshot — a synchronous read, empty until the first load. */
export function getSnapshot(): Snapshot {
  return cache;
}

/** Subscribes to snapshot updates (this is what React's useSyncExternalStore hangs off). */
export function subscribe(fn: () => void): () => void {
  listeners.add(fn);
  return () => listeners.delete(fn);
}

/** Swaps the cache and notifies subscribers — for the return value of a write command, or a mock mutation. */
export function applySnapshot(next: Snapshot): void {
  cache = next;
  inboxDataGeneration++; // real data was swapped in, so the mailbox must re-derive its set.
  for (const l of listeners) l();
}

/**
 * Notifies subscribers without touching the cache — a nudge to refetch. Views pull task_page on
 * demand, so this is the way to re-run the subscribing hooks after a state change that never rides
 * on the snapshot at all (the device-local read last-seen, for instance, which shifts the inbox's
 * unread set). It **does not change inbox membership**, so `inboxDataGeneration` stays put and the
 * mailbox does not recompute.
 */
export function notifyDataChanged(): void {
  for (const l of listeners) l();
}

// Subscribers to "re-ask what does not live in the store". Kept apart from the domain `listeners` for the
// same reason the reflection listeners are: this fires on a wake-up, not on data changing.
const outsideStoreListeners = new Set<() => void>();

/**
 * Subscribes to the moments worth re-asking state that lives **outside** the store — an upstream release,
 * say — and therefore has no store signature to compare. It fires on a focus return that found
 * the store unmoved, which is exactly the hole: every other reconcile ends in `invalidateAllQueries`, so a
 * query for such state is already refetched there and firing again would only ask twice. The returned
 * function unsubscribes.
 */
export function subscribeOutsideStore(fn: () => void): () => void {
  outsideStoreListeners.add(fn);
  return () => outsideStoreListeners.delete(fn);
}

/** Notifies the outside-store subscribers. `focusCatchUp`'s unmoved branch is the only caller. */
function notifyOutsideStore(): void {
  for (const l of outsideStoreListeners) l();
}

/**
 * Notifies that the device-local inbox archive changed. Archiving is the one way out of the inbox,
 * so membership shrinks: bump `inboxDataGeneration` and let the mailbox re-derive its badge count.
 * This differs from `notifyDataChanged` in exactly that — the change reaches the inbox.
 */
export function notifyInboxChanged(): void {
  inboxDataGeneration++;
  for (const l of listeners) l();
}

// The store signature this device saw last, refreshed on every loadSnapshot from the one the snapshot
// itself carries (read by core before the rows, so it is never newer than what is on screen). When a
// store-changed arrives and all three legs still match, the file moved because *we* wrote — the result
// is already on screen — and the snapshot is not read again. This is the watcher's dedup of our own writes;
// the rows still unread on the feed are refetched all the same. Which leg moved is the other half: see `readStoreChange`.
let lastSignature: StoreSignatureDto | null = null;

/** Whether two signatures say the same thing. All three legs, since any one of them moving is a change. */
function sameSignature(a: StoreSignatureDto, b: StoreSignatureDto): boolean {
  return a.file === b.file && a.config === b.config && a.version === b.version;
}

/** Read the signature, or `null` when there is none to have (outside Tauri, or a failed IPC). */
async function readSignature(): Promise<StoreSignatureDto | null> {
  if (!inTauri()) return null;
  try {
    return await invoke<StoreSignatureDto>("store_signature");
  } catch {
    return null; // no signature: fall to the safe side and re-read.
  }
}

/**
 * The window that reads the store when an outside write wakes the app, as long as it is open: the board. The talk
 * window reads only while the board is gone (`app/src-tauri/src/quit.rs`: the board can be closed with the talk
 * window still up). Spelled as `crate::windows::BOARD` spells it.
 */
const BOARD = "main";

/**
 * Carries what the reading window found on one wake to the window that did not read (`followStore`), so a write
 * lands in both windows for one read of the snapshot rather than one per window.
 */
const STORE_REFLECTED = "store-reflected";

/** What the reading window found on one wake, as the other window needs it. See {@link STORE_REFLECTED}. */
interface StoreReflection {
  /** The snapshot as the reader holds it after this wake, or `null` when this wake left it alone. */
  snapshot: Snapshot | null;
  /** The scopes whose queries to refetch, or `"all"` for every live query. */
  scopes: string[] | "all";
  /** Whether inbox membership may have moved. */
  inbox: boolean;
  /** Whether to ask again whether to ask for setup (`recheckSetupAgain`). */
  recheckSetup: boolean;
  /** The outside write that landed, or `null` when none did. */
  reflected: StoreChangeReflected | null;
}

/**
 * Store subscription for the board: when core emits `store-changed` — another process (AI, CLI) wrote — decide what
 * to re-read, and hand what it found to the talk window (`followStore`), which reads nothing of its own while the
 * board is open. That is what keeps one outside write to one read of the snapshot however many windows are up.
 * The returned function unsubscribes.
 */
export async function watchStore(): Promise<() => void> {
  if (!inTauri()) return () => {};
  const { listen, emit } = await import("@tauri-apps/api/event");
  return listen("store-changed", async () => {
    const found = await readStoreChange();
    void emit(STORE_REFLECTED, found).catch(() => {});
  });
}

/**
 * Store subscription for the talk window. While the board is open, take what it read (`watchStore`) and read
 * nothing here. Once the board is gone, read each wake here instead, the way the board would have — or this window
 * would hold the store as it was when the board went. The returned function unsubscribes.
 */
export async function followStore(): Promise<() => void> {
  if (!inTauri()) return () => {};
  const { listen } = await import("@tauri-apps/api/event");
  const { Window } = await import("@tauri-apps/api/window");
  const stopTaking = await listen<StoreReflection>(STORE_REFLECTED, (e) => takeStoreReflection(e.payload));
  const stopReading = await listen("store-changed", async () => {
    const board = await Window.getByLabel(BOARD).catch(() => null);
    if (board !== null) return; // the board reads this one, and hands it over.
    await readStoreChange();
  });
  return () => { stopTaking(); stopReading(); };
}

/** Lay what the board read onto this window, as if this window had read it. */
function takeStoreReflection(r: StoreReflection): void {
  if (r.snapshot !== null) {
    cache = r.snapshot;
    applyPerfConfig(cache.perfLog);
    // So that, should the board go, this window compares the next wake against the store it is drawing.
    lastSignature = r.snapshot.signature;
    if (r.inbox) inboxDataGeneration++;
    for (const l of listeners) l();
  } else if (r.inbox) {
    notifyInboxChanged();
  }
  if (r.scopes === "all") invalidateAllQueries();
  else if (r.scopes.length > 0) invalidateScopes(new Set(r.scopes));
  if (r.recheckSetup) recheckSetupAgain();
  if (r.reflected !== null) notifyStoreChangeReflected(r.reflected);
}

/**
 * One wake of `store-changed`: decide what to re-read from **which leg of the signature moved** (`AMB-D-856`),
 * because `store-changed` is nothing but a wake-up saying *something* did, and the payload never says what:
 *
 * - **nothing moved** … our own write, or an outside one the last `loadSnapshot` already read. The
 *   snapshot region is current, so it is not read again — but the rows past the cursor are still read off
 *   the feed and their scopes refetched: a narrow `loadSnapshot` does not move the cursor, so an outside
 *   write that landed while it read is still there to be found. Rows of our own write come back here too;
 *   refetching what the ack already refetched is the harmless direction. The snapshot this window holds still
 *   goes to the other window: the write may have been this window's, which the other one has not read.
 * - **the store file's identity moved** … it was swapped out from under us (`fold`, `stage_and_swap`, a
 *   restore). Nothing the feed held survives that, so re-read everything. A migration runs in place and
 *   puts what it rewrote on the feed (`AMB-D-1166`), so it comes in as `data_version` alone.
 * - **`config.json`'s identity moved** … that file is not in the database, so no row will ever speak for
 *   it. Re-read everything.
 * - **only `data_version` moved** … somebody committed, and the feed can say what: fold the changed rows'
 *   datasets into scopes and refetch just the queries touching them. A feed that **cannot** say — expired,
 *   a dataset that does not fold, too much piled up — falls back to the full re-read of
 *   `reconcile("gap")`: an invalidation signal is not truth (see `drainChanges`).
 * - **an empty page** … a commit the feed collects no row for: the drive reclaiming the outbox it walked,
 *   a `store_meta` scalar, the feed's own truncation. Read nothing, and announce
 *   nothing — nothing landed on the screen. The one exception is whether to ask for setup again: what
 *   moves it (a send bringing back the server's build) is written off the feed, so an empty page is the
 *   only sign of it, and that one query is asked again (`recheckSetupAgain`).
 *
 * Inbox membership only ever moves on the task side, so the generation is bumped only when `tasks` is
 * among the scopes — an outside write touching decisions or attachments alone must not trigger a mailbox
 * recompute. Returns what was done, for the window that did not read.
 */
async function readStoreChange(): Promise<StoreReflection> {
  const sig = await readSignature();
  const full = async (): Promise<StoreReflection> => {
    await reconcile("gap");
    const reflected: StoreChangeReflected = { reason: "gap", at: Date.now() };
    notifyStoreChangeReflected(reflected);
    return { snapshot: cache, scopes: "all", inbox: true, recheckSetup: false, reflected };
  };
  // No signature at all, or nothing to compare against: we cannot say which leg moved, so re-read.
  if (sig === null || lastSignature === null) return await full();
  const unmoved = sameSignature(sig, lastSignature);
  // The two legs the feed structurally cannot speak for.
  if (!unmoved && (sig.file !== lastSignature.file || sig.config !== lastSignature.config)) return await full();
  const { scopes, gap } = await drainChanges();
  if (gap) return await full();
  const inbox = scopes.has("tasks");
  if (unmoved) {
    // The snapshot on screen already counts every commit up to now, so only the queries the unread rows
    // touched are owed — and the mailbox, when they reach the task side.
    if (scopes.size > 0) {
      invalidateScopes(scopes);
      if (inbox) notifyInboxChanged();
    }
    return { snapshot: cache, scopes: [...scopes], inbox, recheckSetup: false, reflected: null };
  }
  if (scopes.size === 0) {
    // The feed answered, and it named nothing: a commit of the store's own bookkeeping. Nothing
    // lands, so nothing is announced — but the signature is carried forward, or the next wake would
    // be compared against a store two commits old and re-read everything for it.
    lastSignature = sig;
    // A setup, and a send, write the server's build off the feed, so this is the only wake that
    // can carry it — ask again whether to ask for setup, band up or not.
    recheckSetupAgain();
    return { snapshot: null, scopes: [], inbox: false, recheckSetup: true, reflected: null };
  }
  await loadSnapshot({ inboxAffected: inbox });
  invalidateScopes(scopes);
  const reflected: StoreChangeReflected = { reason: "live", at: Date.now() };
  notifyStoreChangeReflected(reflected);
  return { snapshot: cache, scopes: [...scopes], inbox, recheckSetup: false, reflected };
}

/**
 * What can trigger a reconcile. Reconcile is the insurance that closes the holes targeted
 * invalidation can miss, by re-reading from the source of truth (SQLite), and there are exactly
 * three triggers: focus (the window came back — catch up on `store-changed` events that never
 * arrived while backgrounded), manual (the refresh button in the TopBar), and gap (the watcher
 * could not narrow to scopes; raised by `readStoreChange`). Pinned as a type so observability and
 * fault-injection tests can name the last reason.
 */
export type ReconcileReason = "focus" | "manual" | "gap";

let lastReconcile: { reason: ReconcileReason; at: number } | null = null;

/** The reason and time (epoch ms) of the last reconcile, for observability and fault-injection tests; null until one runs. */
export function getLastReconcile(): { reason: ReconcileReason; at: number } | null {
  return lastReconcile;
}

// The reconcile in flight (multiple wake-ups fold into one) and whether another request arrived
// while it ran (run exactly once more afterwards).
let reconcileInFlight: Promise<void> | null = null;
let reconcilePending = false;
// Whether any of the folded wake-ups carried a reason that demands a full re-read (manual, gap). A
// path of nothing but focus can stay a no-op when the signature has not moved; a mix falls to the
// safe side and re-reads everything.
let reconcileForceFull = false;

/**
 * Re-reads state from the source of truth — the snapshot region via `loadSnapshot`, the live queries
 * via invalidation. The trigger decides the granularity:
 *   - manual / gap … a **full re-read** (`invalidateAllQueries`) that trusts no invalidation signal.
 *   - focus … catching up on store-changed events missed while backgrounded. If the store signature
 *     has not moved since the last load, **do nothing** — no indiscriminate invalidation.
 * Overlapping wake-ups (focus and visibility firing together, say) join the one in flight, and a
 * request that arrives during it runs exactly once more afterwards, so nothing is dropped.
 */
export async function reconcile(reason: ReconcileReason): Promise<void> {
  lastReconcile = { reason, at: Date.now() };
  if (reason !== "focus") reconcileForceFull = true; // remember that a full re-read is owed.
  if (reconcileInFlight) {
    reconcilePending = true;
    return reconcileInFlight;
  }
  reconcileInFlight = (async () => {
    try {
      do {
        reconcilePending = false;
        const full = reconcileForceFull;
        reconcileForceFull = false;
        if (full) {
          await loadSnapshot({ whole: true }); // members/projects/activity/config… and lastSignature moves to now.
          invalidateAllQueries(); // every live query — list, board, single, aggregate, decision — re-reads.
        } else {
          await focusCatchUp(); // focus-only path: the signature decides between no-op and a re-read.
        }
      } while (reconcilePending);
    } finally {
      reconcileInFlight = null;
    }
  })();
  return reconcileInFlight;
}

/**
 * One pass of the focus path. Re-reads the store signature and compares it with the last load:
 *   - unchanged → read nothing back (no loadSnapshot, no invalidation, so nothing wakes the mailbox either). The one
 *     thing still asked is the update state, which does not live in the store and so has no signature to move.
 *   - changed, or no signature at all → re-read the snapshot region and every live query. There is
 *     one store, so there is no "where" to narrow by: the signature says only whether it moved.
 * Outside Tauri there is no signature, so this always re-reads everything.
 */
async function focusCatchUp(): Promise<void> {
  const cur = await readSignature();
  if (cur !== null && lastSignature !== null && sameSignature(cur, lastSignature)) {
    // Nothing moved on disk, so there is no snapshot to re-read — but "is there a newer release" does not live in
    // the store, and this is the one moment we get to ask it: the user just came back to the app. Someone who only
    // reads never moves the signature, and would otherwise never be told about an update again after launch.
    await refreshVersionStatus();
    notifyOutsideStore(); // and the same for everything else that lives outside the store.
    return;
  }
  await loadSnapshot({ whole: true }); // this also moves lastSignature to the current value.
  invalidateAllQueries();
}

/**
 * Re-asks core for the update-available state alone and patches it into the snapshot cache. The TTL lives in core
 * (24h), so within the window this answers from its cache without traffic — which is why it is safe to call on every
 * focus return. Failure is silent, the same as everywhere else the update check is surfaced: not being able to say
 * whether an update exists must never get in the way. Outside Tauri there is nothing to ask.
 */
async function refreshVersionStatus(): Promise<void> {
  if (!inTauri()) return;
  let next: VersionStatusDto;
  try {
    next = await invoke<VersionStatusDto>("version_status");
  } catch {
    return; // silent: an update check does not get in the way of the real work.
  }
  const cur = cache.versionStatus;
  if (cur.updateAvailable === next.updateAvailable && cur.newerVersion === next.newerVersion) return; // nothing to redraw.
  cache = { ...cache, versionStatus: next };
  notifyDataChanged(); // the banner is the only reader; inbox membership is untouched.
}

/**
 * The app menu's manual "check for updates" action. Unlike `refreshVersionStatus` (TTL-cached, fired on focus return),
 * this asks core for a **fresh** check that bypasses the cache and the update_check toggle (`check_updates_fresh`),
 * because the user asked explicitly — so it works even for someone who turned automatic checking off. It patches the
 * result into the snapshot cache so the existing update banner reflects it (clearing any prior dismissal when it finds
 * one, so an explicit check surfaces the offer regardless), and returns which of the three outcomes to show as the
 * menu's own transient feedback. Never throws; outside Tauri there is nothing upstream to ask.
 */
export async function checkForUpdatesFresh(): Promise<"available" | "uptodate" | "error"> {
  if (!inTauri()) return "uptodate";
  let next: VersionStatusDto;
  try {
    next = await invoke<VersionStatusDto>("check_updates_fresh");
  } catch {
    return "error"; // the query failed (network, timeout); tell the user rather than claim it is up to date.
  }
  const cur = cache.versionStatus;
  if (
    cur.updateAvailable !== next.updateAvailable ||
    cur.newerVersion !== next.newerVersion ||
    cur.appVersion !== next.appVersion
  ) {
    cache = { ...cache, versionStatus: next };
    notifyDataChanged();
  }
  if (next.updateAvailable) {
    clearDismissedUpdate();
    return "available";
  }
  return "uptodate";
}

// Throttle window for a burst of focus returns, matched to the watcher's 1.5s wake interval. manual and gap are never throttled.
const FOCUS_RECONCILE_THROTTLE_MS = 1500;
let lastFocusReconcileAt = 0;

/**
 * Wires up the one reconcile trigger the DOM can give us: the window regaining focus. The other two
 * call `reconcile` directly and from elsewhere — manual from the TopBar's refresh button, gap from
 * `readStoreChange`. Focus is caught both via visibilitychange→visible and via window focus, and a burst
 * of them is throttled. The DOM path works outside Tauri too. The returned function removes every
 * listener.
 */
export function installReconcileTriggers(): () => void {
  const onFocus = () => {
    const now = Date.now();
    if (now - lastFocusReconcileAt < FOCUS_RECONCILE_THROTTLE_MS) return;
    lastFocusReconcileAt = now;
    void reconcile("focus");
  };
  const onVisible = () => {
    if (typeof document !== "undefined" && document.visibilityState === "visible") onFocus();
  };
  const hasDoc = typeof document !== "undefined";
  const hasWin = typeof window !== "undefined";
  if (hasDoc) document.addEventListener("visibilitychange", onVisible);
  if (hasWin) window.addEventListener("focus", onFocus);
  return () => {
    if (hasDoc) document.removeEventListener("visibilitychange", onVisible);
    if (hasWin) window.removeEventListener("focus", onFocus);
  };
}

/** Granularity of a `loadSnapshot`. By default it counts as inbox-affecting — a wholesale re-read. */
export interface LoadOptions {
  /**
   * Whether this re-read can change inbox membership (default true). When false, `inboxDataGeneration`
   * does not move and the mailbox does not recompute — a change to decisions or attachments alone
   * must not stoke an inbox recompute.
   */
  inboxAffected?: boolean;
  /**
   * Whether every live query is re-read right after this (default false) — `reconcile`'s full re-read. Only
   * then may the change feed's cursor be moved to its head before the read: what the feed held up to there is
   * covered by re-reading everything. A narrower read leaves the cursor where it is, so a row nobody has read
   * yet is still read off the feed (see `readStoreChange`).
   */
  whole?: boolean;
}

// The read in flight, and the one queued behind it. See `loadSnapshot`.
let running: Promise<void> | null = null;
let queued: { inboxAffected: boolean; whole: boolean; done: Promise<void> } | null = null;

/**
 * Re-reads from core (or the fixtures), swaps the cache and notifies subscribers.
 *
 * **Reads never overlap.** A call made while one is in flight does not start a second: it waits for a
 * single read queued behind it, which every call arriving in the meantime joins. That read starts only
 * after each of them was made, so the last caller always sees a store read after it asked. Overlapping
 * reads would instead each overwrite the cache and `lastSignature` whenever their reply came in — the
 * last *reply* would win, not the last *call*, and that order is only kept today because core runs
 * these commands one at a time on the main thread. A queued read is inbox-affecting if any call it
 * stands for was, and whole if any of them was — that caller re-reads every query once it is done.
 */
export function loadSnapshot(opts: LoadOptions = {}): Promise<void> {
  const inboxAffected = opts.inboxAffected ?? true;
  const whole = opts.whole ?? false;
  if (queued) {
    queued.inboxAffected ||= inboxAffected;
    queued.whole ||= whole;
    return queued.done;
  }
  if (running) {
    const next = { inboxAffected, whole, done: Promise.resolve() };
    next.done = running
      .catch(() => {}) // the one before failing is no reason not to read again.
      .then(() => {
        queued = null;
        return startLoad(next.inboxAffected, next.whole);
      });
    queued = next;
    return next.done;
  }
  return startLoad(inboxAffected, whole);
}

function startLoad(inboxAffected: boolean, whole: boolean): Promise<void> {
  const read = readSnapshot(inboxAffected, whole).finally(() => {
    if (running === read) running = null;
  });
  running = read;
  return read;
}

/**
 * One read. On a whole re-read, or when we hold no position yet (startup, a failed IPC), the change feed's
 * position is taken **before** the store is read, not after: a change that slips into the gap would
 * otherwise land behind the cursor and be lost forever. Taking it first can only make a change show up
 * twice, which is the harmless direction. A narrower read leaves the cursor alone — moving it to the head
 * would skip rows that came after the last drain, and with them the queries they touch, which nothing
 * but the feed refetches. Core returns no tasks/decisions rows, so they are filled with empty arrays to
 * satisfy the non-optional type — the Tauri path reads neither, and the paging hooks fetch a window at a
 * time.
 */
async function readSnapshot(inboxAffected: boolean, whole: boolean): Promise<void> {
  if (inTauri()) {
    if (whole || !hasChangeCursor()) await takeChangeCursor();
    const snap = await invoke<Snapshot>("snapshot");
    cache = { ...snap, tasks: snap.tasks ?? [], decisions: snap.decisions ?? [] };
    applyPerfConfig(cache.perfLog);
    lastSignature = snap.signature;
  } else {
    // Browser fallback: build a snapshot of the same shape out of the mock fixtures.
    const fix = await import("../mock/data");
    cache = {
      language: "ja", // the browser fallback runs a Japanese UI (frontend-only iteration)
      dateLocale: null, // …and writes its dates the way that language does
      roster: fix.roster,
      projects: fix.projects,
      tasks: fix.tasks,
      decisions: [], // the mock fixtures carry no decisions
      activity: fix.activity,
      startupHealth: { issues: [] }, // no warnings when iterating in the browser
      versionStatus: { appVersion: "", updateAvailable: false, newerVersion: null }, // and no update check either (the browser fallback asks nothing upstream)
      perfLog: null, // in the browser this is on by default in dev (ipc decides via import.meta.env.DEV)
      updateCheck: true,
      autostart: false, // the browser has no login to register with
      tickConsent: null, // and no scheduler to hold a timer, so the question is never put
      tickRemovalLeavesARow: false, // …so there is no row for a removal to leave behind either
      defaultView: "board",
      signature: { file: "", config: "", version: "" }, // no store behind the fixtures, so nothing to compare
    };
  }
  // Real data came back from the source of truth, so the mailbox owes itself a re-derive — unless the caller said this re-read cannot touch membership.
  if (inboxAffected) inboxDataGeneration++;
  for (const l of listeners) l();
}
